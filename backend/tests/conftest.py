import pytest
import pytest_asyncio
from httpx import AsyncClient, ASGITransport
from sqlalchemy.ext.asyncio import create_async_engine, async_sessionmaker, AsyncSession
from sqlalchemy.pool import StaticPool

from app.main import app
from app.core.database import Base, get_db
from app.seeds.seed_data import seed_initial_data

# Use in-memory SQLite with StaticPool so all connections share the same memory instance
TEST_DB_URL = "sqlite+aiosqlite:///:memory:"

test_engine = create_async_engine(
    TEST_DB_URL,
    connect_args={"check_same_thread": False},
    poolclass=StaticPool,
    echo=False
)

TestSessionLocal = async_sessionmaker(
    bind=test_engine,
    class_=AsyncSession,
    autocommit=False,
    autoflush=False,
    expire_on_commit=False,
)


@pytest_asyncio.fixture(scope="function")
async def db_session():
    # Create all tables
    async with test_engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    # Seed initial test data (Hospital, 5 Doctors, Patients, Appointments, Calls)
    async with TestSessionLocal() as session:
        await seed_initial_data(session)

    # Yield active session for tests
    async with TestSessionLocal() as session:
        yield session

    # Drop tables after test completes
    async with test_engine.begin() as conn:
        await conn.run_sync(Base.metadata.drop_all)


